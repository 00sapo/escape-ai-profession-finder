#!/usr/bin/env python3
"""Precompute title embeddings and offline cosine scores.

Generation uses OpenAI text-embedding-3-large and OPENAI_API_KEY from the
environment or the project .env file. Cached builds and --check use only the
Python standard library and make no API requests. --refresh re-embeds titles.
"""
from __future__ import annotations

import argparse
import gzip
import json
import math
import os
from pathlib import Path
import shlex
import sys
import urllib.error
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
DATASET = ROOT / "web/data/dataset.js"
CACHE = ROOT / "data/cache/semantic-embeddings.json.gz"
OUTPUT = ROOT / "web/data/semantic.js"
MODEL = "text-embedding-3-large"
DIMENSIONS = 3072
PREFIX = "/* generated by pipeline/build_semantic.py, do not edit */\nself.__AI_EXPOSURE_SEMANTIC__ = "


def read_script(path: Path, assignment: str) -> dict:
    text = path.read_text(encoding="utf-8")
    return json.loads(text.split(assignment, 1)[1].strip().removesuffix(";"))


def alignment() -> dict:
    occupations = read_script(DATASET, "self.__AI_EXPOSURE_DATASET__ = ")["occupations"]
    return {"codes": [entry["c"] for entry in occupations],
            "titles": [entry["t"] for entry in occupations],
            "model": MODEL, "provider": "openai",
            "dimensions": DIMENSIONS, "normalization": "l2"}


def validate_cache(cache: dict, expected: dict) -> list[list[float]]:
    for key, value in expected.items():
        if cache.get(key) != value:
            raise ValueError(f"stale embedding cache {key}; regenerate with --refresh")
    vectors = cache.get("vectors", [])
    if len(vectors) != len(expected["codes"]):
        raise ValueError("embedding count does not match occupations")
    for vector in vectors:
        if len(vector) != DIMENSIONS or any(not isinstance(v, (int, float)) or not math.isfinite(v) for v in vector):
            raise ValueError("invalid embedding dimensions or nonfinite vector")
        if abs(sum(v * v for v in vector) - 1) > 1e-5:
            raise ValueError("embedding is not L2 normalized")
    return vectors


def api_key() -> str:
    key = os.environ.get("OPENAI_API_KEY")
    if not key and (ROOT / ".env").exists():
        for line in (ROOT / ".env").read_text(encoding="utf-8").splitlines():
            name, separator, value = line.strip().removeprefix("export ").partition("=")
            if separator and name.strip() == "OPENAI_API_KEY":
                parts = shlex.split(value, comments=True)
                key = parts[0] if len(parts) == 1 else None
                break
    if not key:
        raise ValueError("Set OPENAI_API_KEY in the environment or the project .env file.")
    return key


def embed(titles: list[str]) -> list[list[float]]:
    key = api_key()
    vectors = []
    tokens = 0
    for start in range(0, len(titles), 128):
        batch = titles[start:start + 128]
        payload = json.dumps({
            "model": MODEL, "input": batch,
            "dimensions": DIMENSIONS, "encoding_format": "float",
        }).encode("utf-8")
        request = urllib.request.Request(
            "https://api.openai.com/v1/embeddings", data=payload,
            headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"},
        )
        try:
            with urllib.request.urlopen(request, timeout=120) as response:
                result = json.load(response)
        except urllib.error.HTTPError as error:
            raise ValueError(f"OpenAI embedding request failed with HTTP {error.code}.") from None
        entries = sorted(result["data"], key=lambda entry: entry["index"])
        if [entry["index"] for entry in entries] != list(range(len(batch))):
            raise ValueError("OpenAI response does not match the requested title batch.")
        if result["model"] != MODEL:
            raise ValueError("OpenAI response identifies a different embedding model.")
        for entry in entries:
            vector = entry["embedding"]
            norm = math.sqrt(sum(value * value for value in vector))
            if len(vector) != DIMENSIONS or not math.isfinite(norm) or norm == 0:
                raise ValueError("OpenAI returned an invalid embedding.")
            vectors.append([value / norm for value in vector])
        tokens += result["usage"]["total_tokens"]
        print(f"embedded {len(vectors)}/{len(titles)} profession titles", flush=True)
    print(f"OpenAI embedding usage: {tokens} tokens")
    return vectors


def cosine_matrix(vectors: list[list[float]]) -> list[list[float]]:
    size = len(vectors)
    matrix = [[0.0] * size for _ in range(size)]
    norms = [math.sqrt(sum(v * v for v in vector)) for vector in vectors]
    for i in range(size):
        matrix[i][i] = 1
        for j in range(i):
            score = sum(a * b for a, b in zip(vectors[i], vectors[j])) / (norms[i] * norms[j])
            matrix[i][j] = matrix[j][i] = round(max(0.0, min(1.0, score)), 6)
    return matrix


def validate_matrix(data: dict, expected: dict) -> None:
    for key, value in expected.items():
        if data.get(key) != value:
            raise ValueError(f"stale semantic artifact {key}")
    size = len(expected["codes"])
    matrix = data.get("similarities", [])
    if len(matrix) != size or any(len(row) != size for row in matrix):
        raise ValueError("semantic matrix dimensions do not match occupations")
    for i, row in enumerate(matrix):
        if row[i] != 1:
            raise ValueError("semantic diagonal must equal one")
        for j, value in enumerate(row):
            if not isinstance(value, (int, float)) or not math.isfinite(value) or not 0 <= value <= 1:
                raise ValueError("semantic matrix contains an invalid cosine")
            if value != matrix[j][i]:
                raise ValueError("semantic matrix is not symmetric")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check alignment, vectors, and cached cosine values without API requests")
    parser.add_argument("--refresh", action="store_true", help="replace embeddings using the OpenAI API")
    args = parser.parse_args()
    if args.check and args.refresh:
        parser.error("--check and --refresh cannot be combined")
    expected = alignment()
    if args.refresh or (not CACHE.exists() and not args.check):
        cache = {**expected, "vectors": embed(expected["titles"])}
        validate_cache(cache, expected)
        CACHE.parent.mkdir(parents=True, exist_ok=True)
        CACHE.write_bytes(gzip.compress(json.dumps(cache, separators=(",", ":"), allow_nan=False).encode(), mtime=0))
        print(f"cached {len(cache['vectors'])} embeddings from {MODEL}")
    else:
        with gzip.open(CACHE, "rt", encoding="utf-8") as handle:
            cache = json.load(handle)
        print("reusing cached embeddings (no API requests)")
    vectors = validate_cache(cache, expected)
    matrix = cosine_matrix(vectors)
    if args.check:
        artifact = read_script(OUTPUT, "self.__AI_EXPOSURE_SEMANTIC__ = ")
        validate_matrix(artifact, expected)
        if artifact["similarities"] != matrix:
            raise ValueError("semantic matrix differs from cached embedding cosines")
        print(f"semantic artifacts aligned: {len(vectors)} titles, {DIMENSIONS} dimensions")
    else:
        artifact = {**expected, "similarities": matrix}
        validate_matrix(artifact, expected)
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(PREFIX + json.dumps(artifact, ensure_ascii=False, separators=(",", ":"), allow_nan=False) + ";\n", encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(vectors)} x {len(vectors)})")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError, KeyError, ImportError) as error:
        sys.exit(f"semantic preprocessing failed: {error}")
