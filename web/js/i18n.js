  var DEFAULT = 'it';
  var current = DEFAULT;

  function normalize(tag) {
    if (!tag) {
      return DEFAULT;
    }
    var base = String(tag).toLowerCase().split('-')[0];
    return SUPPORTED.indexOf(base) >= 0 ? base : DEFAULT;
  }

  function detect() {
    if (root.navigator && root.navigator.languages && root.navigator.languages.length > 0) {
      for (var i = 0; i < root.navigator.languages.length; i += 1) {
        var candidate = String(root.navigator.languages[i]).toLowerCase().split('-')[0];
        if (SUPPORTED.indexOf(candidate) >= 0) {
          return candidate;
        }
      }
    }
    return normalize(root.navigator && root.navigator.language);
  }

  function fromHash() {
    var match = /^#(it|en)$/.exec(root.location ? root.location.hash : '');
    return match ? match[1] : null;
  }

  function get() {
    return current;
  }

  var RTL = ['ar'];

  function set(locale) {
    current = normalize(locale);
    if (root.document) {
      root.document.documentElement.lang = current;
      root.document.documentElement.dir = RTL.indexOf(current) >= 0 ? 'rtl' : 'ltr';
    }
    return current;
  }

  function has(key) {
    var table = STRINGS[current] || STRINGS[DEFAULT];
    return table[key] !== undefined || STRINGS[DEFAULT][key] !== undefined;
  }

  function t(key, values) {
    var table = STRINGS[current] || STRINGS[DEFAULT];
    var template = table[key];
    if (template === undefined) {
      template = STRINGS[DEFAULT][key];
    }
    if (template === undefined) {
      return key;
    }
    if (!values) {
      return template;
    }
    return template.replace(/\{(\w+)\}/g, function (match, name) {
      return values[name] === undefined ? match : String(values[name]);
    });
  }

  function number(value, digits) {
    var options = { minimumFractionDigits: digits, maximumFractionDigits: digits };
    try {
      return new Intl.NumberFormat(current, options).format(value);
    } catch (error) {
      return value.toFixed(digits);
    }
  }

  function percent(value) {
    try {
      return new Intl.NumberFormat(current, { style: 'percent', maximumFractionDigits: 0 }).format(value);
    } catch (error) {
      return Math.round(value * 100) + '%';
    }
  }

